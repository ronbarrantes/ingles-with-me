/** Short tips for the sounds Spanish doesn't have, picked from the spelling. */
export function soundTips(w: Word): string[] {
	const tips: string[] = [];
	const en = w.en.toLowerCase();
	if (en.includes("th")) tips.push("th: punta de la lengua entre los dientes");
	if (/v/.test(en)) tips.push("v: dientes de arriba sobre el labio de abajo");
	const say = SAY[w.id] ?? "";
	if (/ii|uu/.test(say)) tips.push("ii / uu: alarga la vocal");
	if (/^j|[^d]j/.test(say) && !tips.length)
		tips.push("j: suave, como un suspiro");
	return tips.slice(0, 2);
}
